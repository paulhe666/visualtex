//! Lookup tables of MathMlToLatexConverter, transcribed by UTF-16 code unit.
//! C# builds them with indexer initializers, so a later duplicate key wins;
//! `build` inserts in source order to keep that rule.

use std::collections::HashMap;
use std::sync::LazyLock;

fn build(entries: &'static [(&'static str, &'static str)]) -> HashMap<&'static str, &'static str> {
    let mut map = HashMap::new();
    for &(key, value) in entries {
        map.insert(key, value);
    }
    map
}

