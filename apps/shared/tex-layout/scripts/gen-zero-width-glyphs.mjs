// Writes src/zero-width-glyphs.ts: the outlines of the characters that are zero wide in their TFM but have ink
// (cmsy/cmbsy \not and \mapstochar, stmaryrd's negation and arrow pieces, newtx's), read from data/glyphs and
// data/profiles/ntx/glyphs. Run from apps/shared/tex-layout: node scripts/gen-zero-width-glyphs.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const tfms = { ...JSON.parse(readFileSync("data/tfm.json", "utf8")), ...JSON.parse(readFileSync("data/profiles/ntx/tfm.json", "utf8")) };
const outlines = {};
for (const dir of ["data/glyphs", "data/profiles/ntx/glyphs"]) {
  for (const file of readdirSync(dir)) {
    const set = JSON.parse(readFileSync(`${dir}/${file}`, "utf8"));
    const tfm = tfms[set.tfm];
    if (!tfm) continue;
    for (const [code, info] of Object.entries(tfm.chars)) {
      const ink = tfm.ink?.[code];
      if (tfm.widths[info[0]] !== 0 || !ink || !(ink[0] > 0 || ink[1] > 0) || !set.glyphs[code]) continue;
      (outlines[set.tfm] ??= { unitsPerEm: set.unitsPerEm, glyphs: {} }).glyphs[code] = set.glyphs[code];
    }
  }
}
const body = JSON.stringify(outlines, Object.keys(outlines).length ? null : undefined, 0);
writeFileSync(
  "src/zero-width-glyphs.ts",
  `// Generated by scripts/gen-zero-width-glyphs.mjs from data/glyphs: do not edit.\n` +
    `// Characters that are zero wide in their font (TeX sets them over the next one: \\\\not before =, \\\\mapstochar\n` +
    `// before \\\\rightarrow): their outlines by TFM name and character code, in units of unitsPerEm (y up).\n` +
    `export const ZERO_WIDTH_GLYPHS: Record<string, { unitsPerEm: number; glyphs: Record<string, string> }> = ${body};\n`,
);
console.log(Object.entries(outlines).map(([name, set]) => `${name}:${Object.keys(set.glyphs).length}`).join(" "));
