#!/usr/bin/env python3
"""Generate the double-struck alphabet the layout engine draws for bbm.sty's \\mathbbm.

The editor's TeX fonts have no blackboard-bold digits or lowercase letters (msbm10 has capitals only), so
\\mathbbm{1} and friends are drawn from the STIX Two Math outlines of the Unicode double-struck alphabet:
U+1D538.. capitals (the seven in Letterlike Symbols: C H N P Q R Z), U+1D552.. lowercase, U+1D7D8.. digits.
The output is a runtime asset (gzip + base64 JSON); the pinned font revision makes it deterministic.

usage: gen-double-struck-glyphs.py [--font STIXTwoMath-Regular.otf] [--output <file>]
"""

from __future__ import annotations

import argparse
import base64
import gzip
import hashlib
import json
import urllib.request
from io import BytesIO
from pathlib import Path

try:
    from fontTools.misc.roundTools import otRound
    from fontTools.pens.boundsPen import BoundsPen
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.ttLib import TTFont
except ImportError as error:  # pragma: no cover
    raise SystemExit("fontTools is required: python3 -m pip install fonttools") from error

# the same pinned revision as the rare-integral outlines
STIX_VERSION = "2.13 b171"
STIX_FONT_URL = "https://raw.githubusercontent.com/stipub/stixfonts/v2.13b171/fonts/static_otf/STIXTwoMath-Regular.otf"
STIX_FONT_SHA256 = "3a5f3f26f40d5698b3c62dd085d48d6663696a3f80825aab8b553d5097518e8c"

LETTERLIKE = {"C": 0x2102, "H": 0x210D, "N": 0x2115, "P": 0x2119, "Q": 0x211A, "R": 0x211D, "Z": 0x2124}


def code_point(char: str) -> int:
    if char.isdigit():
        return 0x1D7D8 + ord(char) - ord("0")
    if char.islower():
        return 0x1D552 + ord(char) - ord("a")
    return LETTERLIKE.get(char, 0x1D538 + ord(char) - ord("A"))


def read_font(path: Path | None) -> bytes:
    if path is not None:
        data = path.read_bytes()
    else:
        request = urllib.request.Request(STIX_FONT_URL, headers={"User-Agent": "VisualTeX-glyph-generator"})
        with urllib.request.urlopen(request, timeout=30) as response:
            data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != STIX_FONT_SHA256:
        raise SystemExit(f"STIX Two Math checksum mismatch: expected {STIX_FONT_SHA256}, received {digest}")
    return data


def glyphs(data: bytes) -> tuple[int, list[dict]]:
    font = TTFont(BytesIO(data), recalcBBoxes=False, recalcTimestamp=False)
    if font["name"].getDebugName(1) != "STIX Two Math" or STIX_VERSION not in (font["name"].getDebugName(5) or ""):
        raise SystemExit(f"the font is not STIX Two Math {STIX_VERSION}")
    units_per_em = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyph_set = font.getGlyphSet()
    out = []
    for char in "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz":
        cp = code_point(char)
        name = cmap.get(cp)
        if name is None:
            raise SystemExit(f"STIX Two Math has no glyph for U+{cp:04X} ({char})")
        bounds = BoundsPen(glyph_set)
        glyph_set[name].draw(bounds)
        if bounds.bounds is None:
            raise SystemExit(f"U+{cp:04X} has no outline")
        _x_min, y_min, _x_max, y_max = (otRound(v) for v in bounds.bounds)
        pen = SVGPathPen(glyph_set, ntos=lambda v: str(otRound(v)))
        glyph_set[name].draw(pen)
        out.append({
            "char": char,
            "codePoint": cp,
            "path": pen.getCommands(),
            "advanceWidth": otRound(font["hmtx"][name][0]),
            "height": max(0, y_max),
            "depth": max(0, -y_min),
        })
    return units_per_em, out


def main() -> int:
    repo = Path(__file__).resolve().parents[4]
    parser = argparse.ArgumentParser()
    parser.add_argument("--font", type=Path, default=None, help="a local copy of the pinned font (else it is downloaded)")
    parser.add_argument("--output", type=Path, default=repo / "apps/shared/visualtex-app/src/math/doubleStruckGlyphs.generatedData.ts")
    args = parser.parse_args()
    units_per_em, glyph_list = glyphs(read_font(args.font))
    payload = json.dumps({"unitsPerEm": units_per_em, "glyphs": glyph_list}, separators=(",", ":"), sort_keys=True).encode()
    digest = hashlib.sha256(payload).hexdigest()
    packed = base64.b64encode(gzip.compress(payload, compresslevel=9, mtime=0)).decode()
    lines = [packed[i:i + 100] for i in range(0, len(packed), 100)]
    args.output.write_text(
        "/*\n"
        " * Generated by apps/shared/tex-layout/scripts/gen-double-struck-glyphs.py from the pinned\n"
        f" * STIX Two Math {STIX_VERSION}: the double-struck alphabet (digits, capitals, lowercase) drawn for\n"
        f" * \\mathbbm. The decoded JSON SHA-256 is {digest}.\n"
        " * The source font is licensed under the SIL Open Font License 1.1.\n"
        " */\n"
        "export const DOUBLE_STRUCK_GLYPHS_GZIP_BASE64 =\n"
        + "\n".join(f'  "{line}"' + (" +" if i < len(lines) - 1 else ";") for i, line in enumerate(lines))
        + "\n",
        encoding="utf-8",
    )
    print(f"{len(glyph_list)} glyphs, {len(packed)} base64 characters, JSON sha256 {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
