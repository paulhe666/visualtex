using System.Collections;
using System.ComponentModel;
using System.Diagnostics;
using System.Runtime.InteropServices;
using System.Text;
using Microsoft.Win32.SafeHandles;

namespace VisualTeX.NativeRenderService;

// Ownership is established before the first child instruction executes. No PID
// baseline, window visibility, command-line classification or name-based killing.
internal sealed class OwnedProcessJob : IDisposable
{
    private readonly SafeFileHandle handle;

    internal OwnedProcessJob()
    {
        handle = CreateJobObject(IntPtr.Zero, null);
        if (handle.IsInvalid) throw new Win32Exception();
        var limits = new ExtendedLimits();
        limits.Basic.LimitFlags = 0x2000; // JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE
        if (!SetInformationJobObject(handle, 9, ref limits, Marshal.SizeOf<ExtendedLimits>()))
        { handle.Dispose(); throw new Win32Exception(); }
    }

    internal int Run(string executable, string manifest, string directory, int timeoutMs, CancellationToken token)
    {
        var environment = new SortedDictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (DictionaryEntry entry in Environment.GetEnvironmentVariables())
            environment[(string)entry.Key] = (string)entry.Value;
        environment["TEMP"] = directory;
        environment["TMP"] = directory;
        environment["DOTNET_BUNDLE_EXTRACT_BASE_DIR"] = Path.Combine(directory, "dotnet");
        var block = string.Join("\0", environment.Select(pair => pair.Key + "=" + pair.Value)) + "\0\0";
        IntPtr nativeEnvironment = Marshal.StringToHGlobalUni(block);
        var startup = new StartupInfo { cb = Marshal.SizeOf<StartupInfo>() };
        ProcessInfo process;
        try
        {
            // Both paths are generated by this service, not supplied by IPC.
            var command = new StringBuilder("\"" + executable + "\" \"" + manifest + "\"");
            if (!CreateProcess(executable, command, IntPtr.Zero, IntPtr.Zero, false,
                    0x08000404, nativeEnvironment, Path.GetDirectoryName(executable), ref startup, out process))
                throw new Win32Exception(); // suspended, Unicode environment, no console
        }
        finally { Marshal.FreeHGlobal(nativeEnvironment); }
        bool assigned = false;
        try
        {
            if (!AssignProcessToJobObject(handle, process.Process)) throw new Win32Exception();
            assigned = true;
            if (ResumeThread(process.Thread) == uint.MaxValue) throw new Win32Exception();
            var clock = Stopwatch.StartNew();
            using (token.Register(() => TerminateJobObject(handle, 125)))
            {
                while (true)
                {
                    token.ThrowIfCancellationRequested();
                    uint wait = WaitForSingleObject(process.Process, 100);
                    if (wait == 0) break;
                    if (wait != 258) throw new Win32Exception();
                    if (clock.ElapsedMilliseconds > timeoutMs) throw new TimeoutException("Native rendering timed out.");
                }
            }
            if (!GetExitCodeProcess(process.Process, out uint code)) throw new Win32Exception();
            return unchecked((int)code);
        }
        finally
        {
            if (!assigned) TerminateProcess(process.Process, 126);
            CloseHandle(process.Thread);
            CloseHandle(process.Process);
        }
    }

    public void Dispose()
    {
        if (handle.IsClosed) return;
        TerminateJobObject(handle, 0);
        // Let the owned native single-instance objects disappear before starting
        // another job. This enumerates only the job, never the system's processes.
        var clock = Stopwatch.StartNew();
        while (clock.ElapsedMilliseconds < 3000
            && QueryInformationJobObject(handle, 1, out Accounting accounting, Marshal.SizeOf<Accounting>(), IntPtr.Zero)
            && accounting.ActiveProcesses != 0) Thread.Sleep(20);
        handle.Dispose();
    }

    [StructLayout(LayoutKind.Sequential)] private struct BasicLimits
    { public long ProcessTime, JobTime; public uint LimitFlags; public UIntPtr MinimumWorkingSet, MaximumWorkingSet; public uint ActiveProcessLimit; public UIntPtr Affinity; public uint PriorityClass, SchedulingClass; }
    [StructLayout(LayoutKind.Sequential)] private struct IoCounters
    { public ulong ReadOperations, WriteOperations, OtherOperations, ReadBytes, WriteBytes, OtherBytes; }
    [StructLayout(LayoutKind.Sequential)] private struct ExtendedLimits
    { public BasicLimits Basic; public IoCounters Io; public UIntPtr ProcessMemory, JobMemory, PeakProcessMemory, PeakJobMemory; }
    [StructLayout(LayoutKind.Sequential)] private struct Accounting
    { public long UserTime, KernelTime, PeriodUserTime, PeriodKernelTime; public uint Faults, TotalProcesses, ActiveProcesses, TerminatedProcesses; }
    [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Unicode)] private struct StartupInfo
    { public int cb; public string? Reserved, Desktop, Title; public uint X, Y, XSize, YSize, XCount, YCount, Fill, Flags; public short Show, ReservedSize; public IntPtr ReservedPointer, Input, Output, Error; }
    [StructLayout(LayoutKind.Sequential)] private struct ProcessInfo
    { public IntPtr Process, Thread; public uint ProcessId, ThreadId; }
    [DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true)] private static extern SafeFileHandle CreateJobObject(IntPtr security, string? name);
    [DllImport("kernel32.dll", SetLastError = true)] private static extern bool SetInformationJobObject(SafeFileHandle job, int kind, ref ExtendedLimits data, int length);
    [DllImport("kernel32.dll", SetLastError = true)] private static extern bool QueryInformationJobObject(SafeFileHandle job, int kind, out Accounting data, int length, IntPtr returned);
    [DllImport("kernel32.dll", SetLastError = true)] private static extern bool AssignProcessToJobObject(SafeFileHandle job, IntPtr process);
    [DllImport("kernel32.dll", SetLastError = true)] private static extern bool TerminateJobObject(SafeFileHandle job, uint code);
    [DllImport("kernel32.dll", CharSet = CharSet.Unicode, SetLastError = true)] private static extern bool CreateProcess(string file, StringBuilder command, IntPtr processSecurity, IntPtr threadSecurity, bool inherit, uint flags, IntPtr environment, string? directory, ref StartupInfo startup, out ProcessInfo process);
    [DllImport("kernel32.dll", SetLastError = true)] private static extern uint ResumeThread(IntPtr thread);
    [DllImport("kernel32.dll", SetLastError = true)] private static extern uint WaitForSingleObject(IntPtr process, uint timeout);
    [DllImport("kernel32.dll", SetLastError = true)] private static extern bool GetExitCodeProcess(IntPtr process, out uint code);
    [DllImport("kernel32.dll")] private static extern bool TerminateProcess(IntPtr process, uint code);
    [DllImport("kernel32.dll")] private static extern bool CloseHandle(IntPtr handle);
}
